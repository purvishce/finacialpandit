from __future__ import annotations

import os
from typing import Any

import psycopg


class FinancialPanditDB:
    """Create and access the Financial Pandit PostgreSQL database."""

    def __init__(self, database_url: str | None = None) -> None:
        self.database_url = database_url or os.environ.get("DATABASE_URL")
        if not self.database_url:
            raise RuntimeError("DATABASE_URL is required before starting the API.")

    def initialize(self) -> None:
        """Create the database schema and indexes if they do not exist."""
        with self.connect() as connection:
            with connection.cursor() as cursor:
                cursor.execute(
                    """
                    CREATE TABLE IF NOT EXISTS transactions (
                        transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        external_transaction_id TEXT,
                        transaction_date DATE NOT NULL,
                        posted_date DATE,
                        description TEXT NOT NULL,
                        merchant TEXT,
                        amount NUMERIC(18, 2) NOT NULL,
                        type TEXT CHECK (
                            type IS NULL OR type IN ('EXPENSE', 'INCOME', 'TRANSFER', 'OTHER')
                        ),
                        category TEXT,
                        confidence NUMERIC(6, 5) CHECK (
                            confidence IS NULL OR confidence BETWEEN 0 AND 1
                        ),
                        needs_review BOOLEAN NOT NULL DEFAULT FALSE,
                        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
                    );
                    CREATE INDEX IF NOT EXISTS idx_transactions_transaction_date
                        ON transactions (transaction_date);
                    CREATE UNIQUE INDEX IF NOT EXISTS idx_transactions_external_id
                        ON transactions (external_transaction_id)
                        WHERE external_transaction_id IS NOT NULL;
                    """
                )

    def connect(self) -> psycopg.Connection[Any]:
        return psycopg.connect(self.database_url, connect_timeout=10)


if __name__ == "__main__":
    FinancialPanditDB().initialize()
    print("PostgreSQL schema initialized.")
